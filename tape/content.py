"""Content for the debrief tape.

Every caption is a list of lines. Lines break exactly where they are written,
the way a character generator broke them: left-aligned, upper case, no terminal
punctuation. These are forms, not sentences.

Tones set typesetting, how long a card holds, and how hard the frame between
cards hits. See TONES in render.py.

Cards are grouped into reels. The hour walks the reels in order, shuffling
within each one, so a given card recurs perhaps every twenty minutes and never
lands near itself.
"""

