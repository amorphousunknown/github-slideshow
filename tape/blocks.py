"""Approved running orders.

Nothing here is shuffled. A block is an explicit, numbered sequence, so what
is reviewed is exactly what is rendered and exactly what appears on the wall.
`content.py` remains the writing pool; a card only reaches a projector by
being listed in a block.

Each card is (lines, tone, impact, risk).

impact  what the card is expected to do to someone who catches it in passing
risk    how a stranger alone on a street at night could take it
          low   reads as fiction, clinical, or about someone else
          med   second person, could feel aimed at the reader
          high  could be taken as a real warning, instruction, or threat
                — these are the ones to decide on deliberately
"""

